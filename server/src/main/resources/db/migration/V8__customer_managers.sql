-- Customer managers (slice 2, ADR D-35): the manager mark and a row ID on memberships, membership
-- requests, and the company an inbox item is about. Rows that exist get their values from the column
-- defaults, so nothing is computed and it runs on the data of v0.2.0 as it is.

-- A membership says whether the customer is a manager of that company; the mark goes with the row
-- (S2-AC-04). row_id names the row in the manager's member list instead of the account ID, which
-- rises in the order accounts were made (S2-AC-10). gen_random_uuid() is built in since PostgreSQL 13
-- and is computed for each row that exists.
ALTER TABLE company_member
    ADD COLUMN manager boolean NOT NULL DEFAULT false,
    ADD COLUMN row_id uuid NOT NULL DEFAULT gen_random_uuid();

ALTER TABLE company_member ADD CONSTRAINT company_member_row_id_key UNIQUE (row_id);

-- Owned by helpdesk (companies). A manager invited an email that already has an account: an admin
-- decides whether that account joins the company (S2-AC-14). A closed request stays, with how it
-- ended. email and name are what the manager typed; the account is never changed by a request. An
-- approved request gives its row_id to the membership it makes (S2-AC-34).
CREATE TABLE membership_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    row_id uuid NOT NULL DEFAULT gen_random_uuid(),
    company_id bigint NOT NULL REFERENCES company (id),
    -- The account that has the email.
    account_id bigint NOT NULL REFERENCES account (id),
    -- The manager who asked.
    requested_by bigint NOT NULL REFERENCES account (id),
    email text NOT NULL,
    name text NOT NULL,
    state text NOT NULL,
    created_at timestamptz NOT NULL,
    closed_at timestamptz,
    -- The admin who approved or rejected, or the manager who withdrew.
    closed_by bigint REFERENCES account (id),
    CONSTRAINT membership_request_row_id_key UNIQUE (row_id),
    CONSTRAINT membership_request_state_check CHECK (state IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN'))
);

-- One open request per company and account: two invitations at the same time make one.
CREATE UNIQUE INDEX membership_request_pending_key ON membership_request (company_id, account_id)
    WHERE state = 'PENDING';

-- The admin's list: open requests, oldest first (S2-AC-33).
CREATE INDEX membership_request_state_idx ON membership_request (state, created_at);

-- The company a MEMBERSHIP_REQUESTED inbox item is about (S2-AC-39); null for the other kinds. The
-- code as text, without a foreign key, like the other IDs notification keeps. notification.kind has no
-- CHECK, so the new kind needs no change here.
ALTER TABLE notification ADD COLUMN company_code text;
