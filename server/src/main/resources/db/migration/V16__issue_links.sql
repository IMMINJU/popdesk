-- Links between two issues (LINK-1 to LINK-7), and the linked issue an inbox item is about. Slice 6c
-- design section 1.

-- Owned by helpdesk (links). One row per pair of issues, whatever its type and direction (LINK-2): the
-- two IDs are stored in the order of the uuid type, smaller first, so the pair has one form. A
-- DUPLICATE_OF link names its duplicate in duplicate_issue_id; the other issue is the original. Removing a
-- link deletes its row; the history of both issues keeps the trace (LINK-7). The issue references have no
-- ON DELETE CASCADE: nothing deletes an issue yet (the trash, slice 7, will delete its links first).
CREATE TABLE issue_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    low_issue_id uuid NOT NULL REFERENCES issue (id),
    high_issue_id uuid NOT NULL REFERENCES issue (id),
    type text NOT NULL,
    -- DUPLICATE_OF: the issue that is the duplicate, one of the two. RELATED: null.
    duplicate_issue_id uuid,
    created_by bigint NOT NULL REFERENCES account (id),
    created_at timestamptz NOT NULL,
    CONSTRAINT issue_link_type_check CHECK (type IN ('DUPLICATE_OF', 'RELATED')),
    CONSTRAINT issue_link_order_check CHECK (low_issue_id < high_issue_id),
    CONSTRAINT issue_link_duplicate_check CHECK (
        (type = 'RELATED' AND duplicate_issue_id IS NULL)
        OR (type = 'DUPLICATE_OF' AND duplicate_issue_id IS NOT NULL
            AND duplicate_issue_id IN (low_issue_id, high_issue_id))),
    -- One link between two issues (S6C-AC-04).
    CONSTRAINT issue_link_pair_key UNIQUE (low_issue_id, high_issue_id)
);

-- The links of an issue from its other side; the unique key serves the low side.
CREATE INDEX issue_link_high_idx ON issue_link (high_issue_id);

-- A duplicate has one original (S6C-AC-05). The service checks it under the lock of both issues first;
-- this keeps a second original out should a write ever miss that lock.
CREATE UNIQUE INDEX issue_link_one_original_idx ON issue_link (duplicate_issue_id)
    WHERE duplicate_issue_id IS NOT NULL;

-- The issue that became RESOLVED or CLOSED, for the items LINKED_ISSUE_RESOLVED and LINKED_ISSUE_CLOSED
-- (S6C-AC-31); null for the other kinds. An ID without a foreign key, like the other IDs this table keeps;
-- the key and the title are read from the issue when the inbox is read (S6C-AC-33).
ALTER TABLE notification ADD COLUMN linked_issue_id uuid;
