-- Labels of a customer company and labels on an issue (LBL-1 to LBL-4), and the due date of an issue
-- (DUE-1). Slice 6a design sections 0 and 1.

CREATE TABLE label (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    company_id bigint NOT NULL REFERENCES company (id),
    -- 1 to 30 characters, without whitespace around it and in Unicode NFC; the app checks the length,
    -- which counts characters as COM-1 does and not as length() does.
    name text NOT NULL,
    -- The name in NFC and lower case (Locale.ROOT), so that "unique whatever the case" does not depend on
    -- the database's collation. The unique key below answers two creations of one name at once with one
    -- 409 (design section 0, 1).
    name_key text NOT NULL,
    color char(7) NOT NULL DEFAULT '#808080',
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT label_company_name_key UNIQUE (company_id, name_key),
    CONSTRAINT label_color_check CHECK (color ~ '^#[0-9A-F]{6}$')
);

-- Deleting a label takes it off every issue in the same statement (LBL-3); deleting an issue takes its
-- labels with it.
CREATE TABLE issue_label (
    issue_id uuid NOT NULL REFERENCES issue (id) ON DELETE CASCADE,
    label_id bigint NOT NULL REFERENCES label (id) ON DELETE CASCADE,
    tenant_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (issue_id, label_id)
);

-- The list filter by label and the count of issues of each label.
CREATE INDEX issue_label_label_idx ON issue_label (label_id, issue_id);

-- A date without a time: the installation's time zone (POPDESK_TIMEZONE) says when it is today.
ALTER TABLE issue ADD COLUMN due_date date;
