-- Tasks of an issue and their notes (TASK-1 to TASK-8), and the task an inbox item or an email is
-- about. Slice 6b design section 1.

-- Owned by helpdesk (tasks). A deleted task keeps its row as a trace (COM-7): title becomes the empty
-- text, the assignee and the due date are cleared, and deleted_at and deleted_by are set. The issue
-- reference has no ON DELETE CASCADE: nothing deletes an issue yet (the trash, slice 7, will delete its
-- tasks first).
CREATE TABLE task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    issue_id uuid NOT NULL REFERENCES issue (id),
    -- 1 to 100 characters; the app checks the length, which counts characters as COM-1 does.
    title text NOT NULL,
    status text NOT NULL,
    assignee_id bigint REFERENCES account (id),
    -- A date without a time, like issue.due_date.
    due_date date,
    created_by bigint NOT NULL REFERENCES account (id),
    created_at timestamptz NOT NULL,
    -- Who made the task DONE and when; both null while it is OPEN (TASK-6).
    done_at timestamptz,
    done_by bigint REFERENCES account (id),
    deleted_at timestamptz,
    deleted_by bigint REFERENCES account (id),
    CONSTRAINT task_status_check CHECK (status IN ('OPEN', 'DONE'))
);

-- The tasks of an issue in the order they were made, and the counts of an issue (S6B-AC-08, S6B-AC-70).
CREATE INDEX task_issue_idx ON task (issue_id, id);

-- The caller's own open tasks (TASK-7), earliest due date first.
CREATE INDEX task_assignee_open_idx ON task (assignee_id, due_date) WHERE status = 'OPEN' AND deleted_at IS NULL;

-- Owned by helpdesk (tasks). One entry of a task: a note a person wrote (NOTE), or a change of one
-- field of the task (CHANGE, TASK-5). A deleted note keeps its row: content becomes the empty text and
-- deleted_at and deleted_by are set. Deleting the task does that to every note and sets old_value and
-- new_value of every change to null.
CREATE TABLE task_note (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    task_id bigint NOT NULL REFERENCES task (id),
    kind text NOT NULL,
    author_id bigint NOT NULL REFERENCES account (id),
    -- The note as written, 1 to 4,000 characters; the empty text for CHANGE and once deleted.
    content text NOT NULL,
    -- CHANGE: STATUS, ASSIGNEE, DUE_DATE, or TITLE. Null for NOTE.
    field text,
    -- CHANGE: the status name, the account ID, the date, or the title, before and after.
    old_value text,
    new_value text,
    created_at timestamptz NOT NULL,
    edited_at timestamptz,
    deleted_at timestamptz,
    deleted_by bigint REFERENCES account (id),
    CONSTRAINT task_note_kind_check CHECK (kind IN ('NOTE', 'CHANGE'))
);

-- The entries of a task in the order they were written, and the counts of a task (S6B-AC-23).
CREATE INDEX task_note_task_idx ON task_note (task_id, id);

-- The task an inbox item or an email is about; null for the other kinds. An ID without a foreign key,
-- like the other IDs these tables keep; the title is read from the task when the inbox is read or the
-- email is sent (S6B-AC-34).
ALTER TABLE notification ADD COLUMN task_id bigint;
ALTER TABLE outbox ADD COLUMN task_id bigint;

-- The items of a task, removed when the task is deleted (S6B-AC-36).
CREATE INDEX notification_task_idx ON notification (task_id) WHERE task_id IS NOT NULL;
