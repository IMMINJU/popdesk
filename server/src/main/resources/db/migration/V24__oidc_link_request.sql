-- OIDC sign-in (AUTH-6). Slice 11 design section 1.

-- Owned by helpdesk (accounts). An account's sign-in with an OIDC provider (AUTH-6): once matched by
-- a verified email, later sign-ins match by issuer and subject only. issuer is the ID token's iss,
-- which equals the discovery document's issuer.
CREATE TABLE oidc_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    account_id bigint NOT NULL REFERENCES account (id),
    issuer text NOT NULL,
    subject text NOT NULL,
    linked_at timestamptz NOT NULL,
    CONSTRAINT oidc_link_issuer_subject_key UNIQUE (issuer, subject),
    CONSTRAINT oidc_link_account_issuer_key UNIQUE (account_id, issuer)
);

-- Owned by helpdesk (accounts). One started OIDC sign-in, used once within 10 minutes. Never the
-- state, the nonce, or the browser value: their SHA-256 as lower-case hex. The PKCE verifier is kept
-- as it is, since the token request sends it. A new start deletes the rows over 10 minutes old.
CREATE TABLE oidc_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    state_hash text NOT NULL,
    browser_hash text NOT NULL,
    nonce_hash text NOT NULL,
    code_verifier text NOT NULL,
    app text NOT NULL,
    next_path text NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT oidc_request_app_check CHECK (app IN ('CONSOLE', 'PORTAL')),
    CONSTRAINT oidc_request_state_hash_key UNIQUE (state_hash)
);
CREATE INDEX oidc_request_created_at_idx ON oidc_request (created_at);
