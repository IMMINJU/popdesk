-- The send queue, operations alerts, channel status, and the cleanup record (first slice).
-- All owned by notification. They hold account and issue IDs without foreign keys: the notification
-- module does not depend on helpdesk's tables, and no table points at these.

-- One row per email or webhook to send (architecture.md "Outbox"). An email row holds the receiving
-- account's ID only; the address and the subject are read when it is sent (MAIL-5).
CREATE TABLE outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    channel text NOT NULL,
    -- What happened, for example INVITATION or ISSUE_CREATED.
    kind text NOT NULL,
    recipient_account_id bigint,
    issue_id uuid,
    comment_id bigint,
    state text NOT NULL,
    attempts integer NOT NULL,
    next_attempt_at timestamptz NOT NULL,
    first_failed_at timestamptz,
    failed_at timestamptz,
    -- A kind such as CONNECTION_REFUSED; never the error text.
    last_error_kind text,
    created_at timestamptz NOT NULL,
    CONSTRAINT outbox_channel_check CHECK (channel IN ('MAIL', 'WEBHOOK')),
    CONSTRAINT outbox_state_check CHECK (state IN ('queued', 'failed')),
    CONSTRAINT outbox_attempts_check CHECK (attempts >= 0)
);

CREATE INDEX outbox_due_idx ON outbox (channel, state, next_attempt_at, id);

-- Last successful send per channel, for the system status (S0-AC-78).
CREATE TABLE delivery_status (
    channel text PRIMARY KEY,
    tenant_id bigint NOT NULL,
    last_success_at timestamptz,
    CONSTRAINT delivery_status_channel_check CHECK (channel IN ('MAIL', 'WEBHOOK'))
);

-- An operations alert that is raised, per kind (S0-AC-80): when it was raised and when admins were
-- last told. The row goes when the alert clears.
CREATE TABLE ops_alert (
    kind text PRIMARY KEY,
    tenant_id bigint NOT NULL,
    raised_at timestamptz NOT NULL,
    last_notified_at timestamptz NOT NULL
);

-- The inbox of a staff account: one row per item (GET /api/console/notifications).
CREATE TABLE notification (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    account_id bigint NOT NULL,
    kind text NOT NULL,
    created_at timestamptz NOT NULL,
    read_at timestamptz
);

CREATE INDEX notification_account_idx ON notification (account_id, id);

-- One row per cleanup job, rewritten each run (S0-AC-82): outbox-failed-cleanup, attachment-cleanup,
-- session-cleanup. helpdesk's jobs write theirs through notification's public API.
CREATE TABLE cleanup_run (
    job text PRIMARY KEY,
    tenant_id bigint NOT NULL,
    last_run_at timestamptz NOT NULL,
    deleted_count bigint NOT NULL,
    CONSTRAINT cleanup_run_deleted_count_check CHECK (deleted_count >= 0)
);
