-- Customer companies, who belongs to them, issues, comments, and attachments (first slice).
-- All owned by helpdesk. The keys follow the lock order of architecture.md section 4.

CREATE TABLE company (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    -- 2 to 10 capital letters and digits; never changes.
    code text NOT NULL,
    name text NOT NULL,
    legal_name text NOT NULL,
    status text NOT NULL,
    -- The number of the company's last issue. Raised with UPDATE ... RETURNING at the end of the
    -- filing transaction (ISSUE-3). No unique index: it would make concurrent filings deadlock.
    last_issue_number integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL,
    CONSTRAINT company_code_key UNIQUE (code),
    CONSTRAINT company_status_check CHECK (status IN ('ACTIVE', 'SUSPENDED', 'ARCHIVED')),
    CONSTRAINT company_last_issue_number_check CHECK (last_issue_number >= 0)
);

-- A customer belongs to a company. Only keys and times (tasks.md section 6: tests remove rows here).
CREATE TABLE company_member (
    company_id bigint NOT NULL REFERENCES company (id),
    account_id bigint NOT NULL REFERENCES account (id),
    tenant_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (company_id, account_id)
);

CREATE INDEX company_member_account_idx ON company_member (account_id);

-- An agent is assigned to a company. Only keys and times.
CREATE TABLE company_agent (
    company_id bigint NOT NULL REFERENCES company (id),
    account_id bigint NOT NULL REFERENCES account (id),
    tenant_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (company_id, account_id)
);

CREATE INDEX company_agent_account_idx ON company_agent (account_id);

CREATE TABLE issue (
    -- Chosen by the app before the row exists, so attachments can point at it first.
    id uuid PRIMARY KEY,
    tenant_id bigint NOT NULL,
    company_id bigint NOT NULL REFERENCES company (id),
    -- The n of the key {company code}-{n}. The row is inserted after the number is taken, so it is
    -- never null.
    number integer NOT NULL,
    title text NOT NULL,
    content text NOT NULL,
    status text NOT NULL,
    priority text NOT NULL,
    is_private boolean NOT NULL,
    reporter_id bigint NOT NULL REFERENCES account (id),
    channel text NOT NULL,
    first_response_at timestamptz,
    -- Goes up by 1 on every change to the row (ISSUE-6).
    version bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    -- The last defence against two issues with one key; the company row lock is the first.
    CONSTRAINT issue_company_number_key UNIQUE (company_id, number),
    CONSTRAINT issue_number_check CHECK (number > 0),
    CONSTRAINT issue_status_check CHECK (status IN ('RECEIVED', 'CONFIRMED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    CONSTRAINT issue_priority_check CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    CONSTRAINT issue_channel_check CHECK (channel IN ('PORTAL', 'EMAIL', 'PHONE', 'OTHER')),
    CONSTRAINT issue_version_check CHECK (version >= 0)
);

CREATE INDEX issue_reporter_idx ON issue (reporter_id);
CREATE INDEX issue_company_created_idx ON issue (company_id, created_at);

CREATE TABLE comment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    issue_id uuid NOT NULL REFERENCES issue (id),
    author_id bigint NOT NULL REFERENCES account (id),
    internal boolean NOT NULL,
    content text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX comment_issue_idx ON comment (issue_id, id);

-- Attachment metadata. The file contents are in attachment_content (POPDESK_STORAGE=db) or in the
-- storage the row names; no bytea here.
CREATE TABLE attachment (
    -- Hard to guess, but not a permission check (ATT-7).
    id uuid PRIMARY KEY,
    tenant_id bigint NOT NULL,
    -- Null while a file for a new issue is pending: the issue row does not exist yet. Deferred, so the
    -- filing transaction can mark the file stored before it inserts the issue (architecture.md section 4).
    issue_id uuid REFERENCES issue (id) DEFERRABLE INITIALLY DEFERRED,
    comment_id bigint REFERENCES comment (id),
    -- Cleared to null when the file is deleted (ATT-5, COM-7).
    file_name text,
    size bigint NOT NULL,
    content_type text NOT NULL,
    state text NOT NULL,
    -- Where the contents are: db, disk, or s3, and the key or path in that storage (S0-AC-56).
    storage text NOT NULL,
    storage_location text,
    uploaded_by bigint NOT NULL REFERENCES account (id),
    created_at timestamptz NOT NULL,
    deleted_at timestamptz,
    deleted_by bigint REFERENCES account (id),
    CONSTRAINT attachment_state_check CHECK (state IN ('pending', 'stored', 'purging', 'purged')),
    CONSTRAINT attachment_storage_check CHECK (storage IN ('db', 'disk', 's3')),
    CONSTRAINT attachment_size_check CHECK (size >= 0),
    CONSTRAINT attachment_stored_has_issue_check CHECK (state = 'pending' OR issue_id IS NOT NULL)
);

CREATE INDEX attachment_issue_idx ON attachment (issue_id);
CREATE INDEX attachment_comment_idx ON attachment (comment_id);
CREATE INDEX attachment_state_created_idx ON attachment (state, created_at);

-- File contents for POPDESK_STORAGE=db, one row per attachment. Written with setBinaryStream and read
-- in 1 MB pieces with substring (architecture.md "Attachment storage").
CREATE TABLE attachment_content (
    attachment_id uuid PRIMARY KEY REFERENCES attachment (id),
    tenant_id bigint NOT NULL,
    data bytea NOT NULL
);
