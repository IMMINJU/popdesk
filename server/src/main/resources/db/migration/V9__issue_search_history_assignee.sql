-- Issues, slice 3: the trigram extension for the search, the assignee, who filed on behalf, the
-- resolved and closed times, the text the search looks in, the history of an issue, and the keys
-- that keep a filing from happening twice.
--
-- This migration cannot be undone: an older popdesk does not start on this schema (ADR D-24, D-46).

-- The search uses trigram indexes (ADR D-13). The owner of the database may create this extension;
-- where the app's user may not, a database administrator creates it first and this line passes
-- (S3-AC-91). io.popdesk.MigrationStart tells the operator what to run when it fails.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

ALTER TABLE issue
    -- Null when nobody is assigned (ISSUE-7).
    ADD COLUMN assignee_id bigint REFERENCES account (id),
    -- The staff member who filed the issue for the reporter; null when the reporter filed it (ADR D-34).
    ADD COLUMN created_by bigint REFERENCES account (id),
    ADD COLUMN resolved_at timestamptz,
    ADD COLUMN closed_at timestamptz,
    -- The title, a line break, and the text the content shows without its Markdown marks (ADR D-56).
    -- Written by the app with the title and the content; V10 fills the issues that are there, and V11
    -- builds the index after that.
    ADD COLUMN search_text text NOT NULL DEFAULT '';

CREATE INDEX issue_assignee_idx ON issue (assignee_id) WHERE assignee_id IS NOT NULL;
CREATE INDEX issue_status_created_idx ON issue (status, created_at);

-- One row per field that changed (HIST-1). Values are text: the name of a status or priority, the
-- account ID of an assignee, the title or content as it was.
CREATE TABLE issue_history (
    -- Entries of an issue are in the order of their IDs.
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    issue_id uuid NOT NULL REFERENCES issue (id),
    kind text NOT NULL,
    -- STATUS, ASSIGNEE, TITLE, CONTENT, PRIORITY; later slices add names, so there is no list here.
    -- Null for CREATED, like both values.
    field text,
    old_value text,
    new_value text,
    -- An account ID, or 0 for popdesk itself. No foreign key: there is no account 0.
    actor_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT issue_history_kind_check CHECK (kind IN ('CREATED', 'CHANGED'))
);

CREATE INDEX issue_history_issue_idx ON issue_history (issue_id, id);

-- Every issue that is there was filed on the portal by its reporter.
INSERT INTO issue_history (tenant_id, issue_id, kind, actor_id, created_at)
SELECT tenant_id, id, 'CREATED', reporter_id, created_at
FROM issue
ORDER BY created_at, id;

-- The Idempotency-Key of a filing, kept for 24 hours (ISSUE-12). The key belongs to the account.
CREATE TABLE issue_idempotency (
    tenant_id bigint NOT NULL,
    account_id bigint NOT NULL REFERENCES account (id),
    key text NOT NULL,
    -- SHA-256 of the fields of the filing, to tell a retry from another filing with the same key.
    request_hash text NOT NULL,
    -- Deferred like the attachments' key: the row is written before the issue row in the filing
    -- transaction (architecture.md section 4).
    issue_id uuid NOT NULL REFERENCES issue (id) DEFERRABLE INITIALLY DEFERRED,
    created_at timestamptz NOT NULL,
    PRIMARY KEY (account_id, key)
);

CREATE INDEX issue_idempotency_created_idx ON issue_idempotency (created_at);

-- The account search (name, email) with the same kind of index (S3-AC-17).
CREATE INDEX account_name_trgm_idx ON account USING gin (name gin_trgm_ops);
CREATE INDEX account_email_trgm_idx ON account USING gin (email gin_trgm_ops);
