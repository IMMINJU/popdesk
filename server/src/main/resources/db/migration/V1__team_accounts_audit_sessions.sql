-- Team, accounts, invitations, the audit log, and Spring Session's tables (first slice).
--
-- Every business table has tenant_id bigint NOT NULL (ADR D-18); the exceptions are listed in
-- server/README.md. Times are timestamptz and come from the app's Clock, never from now().

-- The team itself. The app inserts team 1 after the migrations (S0-AC-01).
CREATE TABLE tenant (
    id bigint PRIMARY KEY,
    name text NOT NULL,
    created_at timestamptz NOT NULL
);

-- Owned by helpdesk (accounts). id 0 is never used: the audit log names the system as account 0.
CREATE TABLE account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    -- Stored trimmed, as entered. Sign-in and the duplicate check ignore case (AUTH-1).
    email text NOT NULL,
    name text NOT NULL,
    role text NOT NULL,
    status text NOT NULL,
    -- Argon2id in its text form ($argon2id$...). Null until an invitation is accepted.
    password_hash text,
    -- Language of the account's email (en, ko, ...).
    locale text NOT NULL,
    failed_sign_ins integer NOT NULL DEFAULT 0,
    locked_until timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT account_role_check CHECK (role IN ('CUSTOMER', 'AGENT', 'ADMIN')),
    CONSTRAINT account_status_check CHECK (status IN ('INVITED', 'ACTIVE', 'SUSPENDED')),
    CONSTRAINT account_failed_sign_ins_check CHECK (failed_sign_ins >= 0)
);

-- One account per email, ignoring case. A duplicate invitation is answered by this name (409).
CREATE UNIQUE INDEX account_email_key ON account (lower(email));

-- Owned by helpdesk (accounts). The open invitation of an INVITED account; deleted on accept.
CREATE TABLE invitation (
    account_id bigint PRIMARY KEY REFERENCES account (id),
    tenant_id bigint NOT NULL,
    -- SHA-256 of the 32-byte token, as lower-case hex. Never the token (S0-AC-35).
    token_hash text NOT NULL,
    invited_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    CONSTRAINT invitation_token_hash_key UNIQUE (token_hash)
);

-- Owned by helpdesk (audit log). No table points at it: rows are kept as written (S0-AC-83, S0-AC-100).
CREATE TABLE audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    action text NOT NULL,
    -- {"accountId": ..., "name": ..., "email": ...}; the system is {"accountId": 0, "name": null, "email": null}.
    actor jsonb NOT NULL,
    target jsonb,
    changes jsonb,
    occurred_at timestamptz NOT NULL
);

CREATE INDEX audit_log_occurred_at_idx ON audit_log (occurred_at);

-- Spring Session JDBC, in the shape its PostgreSQL schema script gives (architecture.md section 5).
CREATE TABLE spring_session (
    primary_id char(36) NOT NULL,
    session_id char(36) NOT NULL,
    creation_time bigint NOT NULL,
    last_access_time bigint NOT NULL,
    max_inactive_interval int NOT NULL,
    expiry_time bigint NOT NULL,
    principal_name varchar(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id char(36) NOT NULL,
    attribute_name varchar(200) NOT NULL,
    attribute_bytes bytea NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
