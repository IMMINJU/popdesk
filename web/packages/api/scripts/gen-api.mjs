// Generates TypeScript types from the two OpenAPI files (ADR D-21, D-43).
// POPDESK_OPENAPI_DIR points at another folder holding openapi-portal.json
// and openapi-console.json; it defaults to docs/integrate.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const specDir = resolve(pkgRoot, process.env.POPDESK_OPENAPI_DIR ?? '../../../docs/integrate');
const outDir = resolve(pkgRoot, 'src/generated');

const header = '// Generated by `pnpm gen:api` from docs/integrate/openapi-%s.json. Do not edit.\n\n';

await mkdir(outDir, { recursive: true });
for (const app of ['portal', 'console']) {
  const spec = JSON.parse(await readFile(resolve(specDir, `openapi-${app}.json`), 'utf8'));
  const ast = await openapiTS(spec);
  // LF on every OS, so a run on Windows leaves no line-ending changes.
  const text = (header.replace('%s', app) + astToString(ast)).replace(/\r\n/g, '\n');
  await writeFile(resolve(outDir, `${app}.ts`), text);
  console.log(`generated src/generated/${app}.ts`);
}
